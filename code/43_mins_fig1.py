"""MINS orthopaedic paper — Fig 1 cohort flow diagram (English, 300 dpi).

SUPERSEDED (2026-11-13): Fig 1 is now generated by 61_r_fig1_flow.R (R/grid port
with revised wording). This file is kept for provenance; do not use it for the
submission build.

B4 redesign: the FULL COHORT is the trunk (top box -> full-cohort secondary
outcomes), and the troponin-monitored subset is a branch hanging off it, so the
figure reads as "what happens to everyone" with the primary MINS analysis
visualised as a selected subpopulation.
"""
import os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch

OUT = "output"
FIG = os.path.join(OUT, "figures", "submission")
BLUE, AMBER, GREY = "#1f5c8b", "#8a6d3b", "#7a7a7a"
plt.rcParams.update({
    "font.family": "DejaVu Sans", "font.size": 8, "savefig.dpi": 300,
})

fig, ax = plt.subplots(figsize=(7.4, 5.3))
ax.set_xlim(-1.15, 11.70); ax.set_ylim(2.15, 8.45); ax.axis("off")

LX, RX, W = 0.0, 5.55, 4.75          # column origin / width
MON_W, MON_X_OFF = 2.90, 0.0          # monitored branch box width
NOT_X, NOT_W = 3.05, 1.70             # not-monitored box position within column


def box(x, y, w, h, text, fc="#eef3f8", ec=BLUE, fs=6.2, ls="-"):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle="round,pad=0.06,rounding_size=0.10",
                                fc=fc, ec=ec, lw=0.8, ls=ls))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=fs,
            linespacing=1.45)


def varrow(x, y1, y2):
    ax.annotate("", xy=(x, y2), xytext=(x, y1),
                arrowprops=dict(arrowstyle="-|>", lw=0.8, color="#555",
                                shrinkA=1, shrinkB=1))


def elbow(x0, y0, xm, y1, x1):
    """Polyline (x0,y0) -> (xm,y0) -> (xm,y1) -> arrow into (x1,y1)."""
    ax.plot([x0, xm], [y0, y0], lw=0.9, color="#555")
    ax.plot([xm, xm], [y0, y1], lw=0.9, color="#555")
    ax.annotate("", xy=(x1, y1), xytext=(xm, y1),
                arrowprops=dict(arrowstyle="-|>", lw=0.9, color="#555",
                                shrinkA=0, shrinkB=1))


ax.text(LX, 8.30, "Derivation cohort", fontsize=7.8, weight="bold")
ax.text(RX, 8.30, "External validation cohort", fontsize=7.8, weight="bold")


def column(cx, top_text, mon_text, excl_text, anal_text, notmon_text, full_text):
    # ---- trunk: top full-cohort box ----
    box(cx, 7.28, W, 0.80, top_text, "#dbe8f2", BLUE, fs=6.6)
    # ---- branch: monitored subset (left half) ----
    box(cx + MON_X_OFF, 6.02, MON_W, 0.95, mon_text, "#eef3f8", BLUE, fs=6.0)
    box(cx + MON_X_OFF, 4.72, MON_W, 1.02, excl_text, "#f7f7f7", GREY, fs=5.6)
    box(cx + MON_X_OFF, 3.60, MON_W, 0.88, anal_text, "#dbe8f2", BLUE, fs=6.2)
    # ---- not-monitored (right half, dashed grey) ----
    b = FancyBboxPatch((cx + NOT_X, 6.10), NOT_W, 0.80,
                       boxstyle="round,pad=0.05,rounding_size=0.08",
                       fc="#f5f5f5", ec=GREY, lw=0.7, ls=(0, (3, 2)))
    ax.add_patch(b)
    ax.text(cx + NOT_X + NOT_W / 2, 6.50, notmon_text, ha="center", va="center",
            fontsize=5.7, color="#444", linespacing=1.4)
    # ---- arrows: top -> branch / top -> not-monitored; branch chain ----
    varrow(cx + MON_X_OFF + MON_W / 2, 7.26, 7.00)
    varrow(cx + MON_X_OFF + MON_W / 2, 6.00, 5.76)
    varrow(cx + MON_X_OFF + MON_W / 2, 4.70, 4.50)
    ax.annotate("", xy=(cx + NOT_X + NOT_W / 2, 6.92), xytext=(cx + NOT_X + NOT_W / 2, 7.26),
                arrowprops=dict(arrowstyle="-|>", lw=0.7, color=GREY, ls=(0, (3, 2)),
                                shrinkA=1, shrinkB=1))
    # ---- trunk continues down the outer side to the full-cohort outcomes box ----
    if cx == LX:
        elbow(cx, 7.68, -0.55, 2.72, cx)          # left column: outer side = far left
    else:
        elbow(cx + W, 7.68, cx + W + 0.55, 2.72, cx + W)  # right column: far right
    # ---- bottom full-width box: secondary outcomes, whole cohort ----
    box(cx, 2.28, W, 0.88, full_text, "#f4ece3", AMBER, fs=6.0)


# ---------------- INSPIRE ----------------
column(LX,
    "INSPIRE registry (single centre, Seoul)\n"
    "Orthopaedic operations (department\n"
    "= Orthopedic Surgery): n = 10,002",
    "Postoperative troponin\n"
    "monitored (\u22651 cTnI, 0\u201372 h\n"
    "after surgery)\nn = 468 (4.7%)",
    "Excluded (n = 34):\n"
    "\u2022 missing ASA class (n = 33)\n"
    "\u2022 missing baseline creatinine (n = 1)\n"
    "(retained: BMI imputed, n = 12)",
    "Primary MINS analysis\n"
    "n = 434 monitored patients\n"
    "MINS 155 (35.7%)",
    "Not monitored\nn = 9,534 (95.3%)\nMINS not\nascertainable",
    "Secondary-outcome model cohorts\n(complete covariates; no troponin required):\n"
    "AKI n = 8,306, 317 events (3.8%);\n"
    "in-hospital death n = 9,491, 94 events (1.0%)")

# ---------------- MOVER ----------------
column(RX,
    "MOVER registry (single centre, UC Irvine)\n"
    "Orthopaedic operations\n"
    "(184 OP procedure codes): n = 6,940",
    "Postoperative troponin\n"
    "monitored (platform MINS\n"
    "flag; peak hs-TnI)\nn = 230 (3.3%)",
    "Excluded (n = 4):\n"
    "\u2022 no intraoperative MAP record\n"
    "   (burden unavailable)\n"
    "(retained: BMI imputed, n = 21)",
    "Primary MINS analysis\n"
    "n = 226 monitored patients\n"
    "MINS 102 (45.1%)",
    "Not monitored\nn = 6,710 (96.7%)\nMINS not\nascertainable",
    "Secondary-outcome model cohorts\n(complete covariates; no troponin required):\n"
    "AKI n = 5,351, 780 events (14.6%);\n"
    "in-hospital death n = 6,199, 20 events (0.3%)")

ax.text(LX, 2.05,
        "MINS = myocardial injury after noncardiac surgery (INSPIRE: peak cTnI >0.026 ng/mL within 72 h;\n"
        "MOVER: platform-derived MINS flag). AKI = KDIGO stage 1+ within 7 days. MAP = mean arterial pressure.\n"
        "Troponin was measured at the discretion of the treating team, not per protocol; the primary analysis is\n"
        "restricted to the monitored branch. Secondary-outcome model samples require complete covariates but not\n"
        "troponin monitoring; AKI additionally requires evaluable pre- and postoperative creatinine.",
        fontsize=5.6, color="#444", va="top", linespacing=1.55)

fig.savefig(os.path.join(FIG, "MINS_Fig1_flow.png"), dpi=300,
            bbox_inches="tight", facecolor="white")
plt.close(fig)
print("-> MINS_Fig1_flow.png")
